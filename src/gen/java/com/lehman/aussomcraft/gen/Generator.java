    /**
     * Writes one Aussom module per type per tier, so a script includes only
     * what it touches and an engine parses only that.
     */
    private void writeAussom(Class<?> Type, String Simple,
            Map<Tier, List<Method>> ByTier) throws IOException {
        for (Tier t : Tier.values()) {
            List<Method> ms = new ArrayList<Method>();
            for (Tier u : Tier.values()) {
                if (t.includes(u)) {
                    ms.addAll(ByTier.get(u));
                }
            }
            if (ms.isEmpty()) {
                continue;
            }

            // Named once, used by both writers, so the Aussom declaration and
            // the Java method it binds can never disagree.
            List<Named> named = this.assignNames(Type, ms);
            this.writeJavaShim(Type, t, named);

            String shim = SHIM_PKG + "." + t.getId() + "." + Simple + "Shim";
            this.emitted.get(t).add(Type.getName());

            StringBuilder sb = new StringBuilder();
            sb.append(header());
            sb.append("/**\n * Generated shim for ").append(Type.getName())
              .append(".\n");
            sb.append(" *\n * Paper: ").append(this.javadocUrl(Type)).append('\n');
            String parents = this.parentText(Type, t);
            if (parents != null) {
                sb.append(" *\n");
                for (String line : wrap("In Paper this is " + parents + ".", 66)) {
                    sb.append(" * ").append(line).append('\n');
                }
                sb.append(" * Every method it inherits is declared here too, so there is\n");
                sb.append(" * nothing to follow up to.\n");
            }
            sb.append(" *\n * Tier: ").append(t.getId()).append(". Do not edit.\n */\n");
            sb.append("extern class ").append(Simple).append(" : ")
              .append(shim).append(" {\n");

            // Equality compares the wrapped objects, so two shims handed out
            // for the same player are the same to a script. != needs nothing:
            // it defaults to negating this.
            Set<String> seen = new HashSet<String>();
            seen.add("__opEq__/1");
            sb.append("    public extern __opEq__(A0);\n");

            for (Named nm : named) {
                String sig = nm.name + "/" + nm.method.getParameterCount();
                if (!seen.add(sig)) {
                    // Only reachable if naming produced a duplicate, which it
                    // is written not to. Dropping is safer than emitting a
                    // module that will not parse.
                    this.bump("dropped, duplicate extern name");
                    continue;
                }
                sb.append(this.docComment(Type, nm.method, t));
                sb.append("    public extern ").append(nm.name).append("(");
                List<String> names = this.argNames(Type, nm.method);
                for (int i = 0; i < names.size(); i++) {
                    if (i > 0) {
                        sb.append(", ");
                    }
                    sb.append(names.get(i));
                }
                sb.append(");\n");
            }
            sb.append("}\n");
            Path dir = this.ausOut.resolve(t.getId());
            Files.createDirectories(dir);
            Files.write(dir.resolve(Simple + ".aus"),
                sb.toString().getBytes(StandardCharsets.UTF_8));
        }
    }

    /**
     * Deletes an output directory and everything under it.
     *
     * Whole directory rather than file by file, so nothing can outlive a
     * regeneration. A shim left behind for a type Paper has dropped would
     * still be loadable and still callable from a script, and matching on
     * file contents to decide what to remove is a rule that can be got
     * wrong. Nothing hand written lives in either output directory.
     *
     * @param Root is the directory to clear.
     * @return An int with how many files were removed.
     * @throws IOException on a delete failure.
     */
    public static int wipe(Path Root) throws IOException {
        if (!Files.isDirectory(Root)) {
            return 0;
        }
        String leaf = Root.getFileName().toString();
        boolean ok = false;
        for (String allowed : DELETABLE) {
            if (leaf.equals(allowed)) {
                ok = true;
            }
        }
        if (!ok) {
            throw new IOException("refusing to delete '" + Root
                + "': the generator only clears directories named "
                + Arrays.toString(DELETABLE) + ", and this looks like a mistyped path");
        }

        List<Path> all = new ArrayList<Path>();
        try (java.util.stream.Stream<Path> walk = Files.walk(Root)) {
            for (Path f : (Iterable<Path>) walk::iterator) {
                all.add(f);
            }
        }
        // Deepest first, so a directory is empty by the time it is removed.
        Collections.sort(all, (a, b) -> b.getNameCount() - a.getNameCount());
        int files = 0;
        for (Path f : all) {
            if (f.equals(Root)) {
                continue;
            }
            if (Files.isRegularFile(f)) {
                files++;
            }
            Files.delete(f);
        }
        return files;
    }

    /**
     * Documentation for a method, looked up where it is declared.
     *
     * A type inherits most of its methods, and the sources describe them on
     * the interface that declares them rather than on every type that has
     * them. Player.openWorkbench is documented on HumanEntity, so looking
     * only at the generating type finds nothing for the majority of an
     * inherited API.
     */
    private Docs.MethodDoc docFor(Class<?> Type, Method M) {
        if (this.docs == null) {
            return null;
        }
        Docs.MethodDoc doc = this.docs.lookup(M.getDeclaringClass().getName(),
            M.getName(), M.getParameterTypes());
        if (doc != null) {
            return doc;
        }
        return this.docs.lookup(Type.getName(), M.getName(), M.getParameterTypes());
    }

    /**
     * Argument names for a method, from the sources jar. Falls back to A0,
     * A1 when the sources do not describe it.
     */
    private List<String> argNames(Class<?> Type, Method M) {
        List<String> out = new ArrayList<String>();
        Docs.MethodDoc doc = this.docFor(Type, M);
        for (int i = 0; i < M.getParameterCount(); i++) {
            if (doc != null && doc.params.size() == M.getParameterCount()) {
                out.add(doc.params.get(i));
            } else {
                out.add("A" + i);
            }
        }
        return out;
    }

    /**
     * An Aussom doc comment for a method, built from Paper's javadoc and the
     * method's own types.
     *
     * Types are written into the text because Aussom cannot carry them in
     * the signature: a parameter may only be declared with a primitive type.
     * Where a type has a module in this tier the name is written as a
     * Markdown link, which survives into the generated documentation. Links
     * are authored here rather than matched afterwards, so a type name that
     * is also an ordinary word, such as Action or Set, is never linked by
     * accident.
     */
    /**
     * The doc comment for one generated method.
     *
     * Deliberately says nothing about what the method does. Paper's own
     * descriptions are GPL 3.0 and this project is Apache 2.0, so they are
     * linked rather than copied. What is written here is this project's own
     * words about types, plus the parameter names, which are needed to call
     * the method at all.
     */
    private String docComment(Class<?> Type, Method M, Tier At) {
        List<String> names = this.argNames(Type, M);
        Class<?>[] params = M.getParameterTypes();
        boolean returns = !M.getReturnType().equals(void.class);

        StringBuilder sb = new StringBuilder();
        sb.append("\n    /**\n");
        sb.append("     * Paper: ").append(this.javadocUrl(Type, M)).append('\n');

        if (!names.isEmpty() || returns) {
            sb.append("     *\n");
        }
        for (int i = 0; i < names.size(); i++) {
            String n = names.get(i);
            String type = this.typeText(params[i], At);
            String line = "@p " + n + " is " + article(type) + " " + type + ".";
            for (String out : wrap(line, 66)) {
                sb.append("     * ").append(out).append('\n');
            }
        }
        if (returns) {
            String type = this.typeText(M.getReturnType(), At);
            String line = "@r " + upper(article(type)) + " " + type + ".";
            for (String out : wrap(line, 66)) {
                sb.append("     * ").append(out).append('\n');
            }
        }
        sb.append("     */\n");
        return sb.toString();
    }

    /**
     * The Paper types this one comes from, as links.
     *
     * The Aussom classes are flat, because the interpreter allows only one
     * external class in an inheritance chain, so a page would otherwise
     * show "extends: object" and say nothing about where the type sits.
     * Only parents with a module in this tier are named.
     *
     * @param Type is the type being written.
     * @param At is the tier being written.
     * @return A String naming the parents, or null when there are none.
     */
    private String parentText(Class<?> Type, Tier At) {
        java.util.Set<String> seen = new java.util.LinkedHashSet<String>();
        for (Class<?> i : Type.getInterfaces()) {
            String simple = i.getSimpleName();
            if (Rules.isGenerated(i) && this.tierTypes.get(At).contains(simple)
                    && !simple.equals(Type.getSimpleName())) {
                seen.add("[" + simple + "](" + simple + ".aus.md)");
            }
        }
        Class<?> sup = Type.getSuperclass();
        if (sup != null && Rules.isGenerated(sup)
                && this.tierTypes.get(At).contains(sup.getSimpleName())) {
            seen.add("[" + sup.getSimpleName() + "](" + sup.getSimpleName() + ".aus.md)");
        }
        if (seen.isEmpty()) {
            return null;
        }
        List<String> parts = new ArrayList<String>(seen);
        if (parts.size() == 1) {
            return "a " + parts.get(0);
        }
        String last = parts.remove(parts.size() - 1);
        return "a " + String.join(", ", parts) + " and " + last;
    }

    /**
     * How a type is written in a doc comment.
     *
     * A type with a module in this tier becomes a link to it. A type without
     * one is named plainly, which is what keeps a tier from pointing at
     * something it does not have. Enums arrive as their name, so they are
     * described as a string, with a link to the page listing the values.
     */
    private String typeText(Class<?> T, Tier At) {
        if (T == null) {
            return "value";
        }
        if (T.equals(void.class)) {
            return "nothing";
        }
        if (T.equals(boolean.class) || T.equals(Boolean.class)) {
            return "bool";
        }
        if (T.equals(String.class) || T.equals(CharSequence.class)
                || T.equals(java.util.UUID.class)) {
            return "string";
        }
        if (T.equals(double.class) || T.equals(float.class)
                || T.equals(Double.class) || T.equals(Float.class)) {
            return "double";
        }
        if (T.isPrimitive() || Number.class.isAssignableFrom(T)) {
            return "int";
        }
        if (java.util.Collection.class.isAssignableFrom(T) || T.isArray()) {
            return "list";
        }
        if (java.util.Map.class.isAssignableFrom(T)) {
            return "map";
        }

        String simple = T.getSimpleName();

        // A nested type's simple name does not say whose it is. Result is
        // declared on AsyncPlayerPreLoginEvent, BlockLockCheckEvent and a
        // dozen others, and every one of them read "a string naming a
        // Result", so two overloads taking different Result enums carried
        // identical documentation and a reader could not tell them apart.
        //
        // Only the displayed name is qualified. The link key stays the
        // simple name, because a generated module is named by it.
        String shown = simple;
        if (T.getEnclosingClass() != null) {
            shown = T.getEnclosingClass().getSimpleName() + "." + simple;
        }

        if (T.isEnum()) {
            if (this.tierTypes.get(At).contains(simple)) {
                return "string naming " + article(simple)
                    + " [" + simple + "](" + simple + ".aus.md)";
            }
            return "string naming " + article(shown) + " " + shown;
        }
        if (this.tierTypes.get(At).contains(simple)) {
            return "[" + simple + "](" + simple + ".aus.md)";
        }
        return shown;
    }

    /** "a" or "an", read off the first letter a reader will actually see. */
    private static String article(String TypeText) {
        String bare = TypeText;
        int link = bare.indexOf('[');
        if (link >= 0) {
            bare = bare.substring(link + 1);
        }
        if (bare.isEmpty()) {
            return "a";
        }
        char c = Character.toLowerCase(bare.charAt(0));
        if (c == 'a' || c == 'e' || c == 'i' || c == 'o' || c == 'u') {
            return "an";
        }
        return "a";
    }

    /** Ends a sentence, without doubling a stop the javadoc already had. */
    private static String ensureStop(String Line) {
        String s = Line.trim();
        if (s.endsWith(".") || s.endsWith("!") || s.endsWith("?")) {
            return s;
        }
        return s + ".";
    }

    /** Wraps text to a width, so generated comments stay readable. */
    private static List<String> wrap(String Text, int Width) {
        List<String> out = new ArrayList<String>();
        StringBuilder line = new StringBuilder();
        for (String word : Text.split(" ")) {
            if (line.length() > 0 && line.length() + word.length() + 1 > Width) {
                out.add(line.toString());
                line = new StringBuilder();
            }
            if (line.length() > 0) {
                line.append(' ');
            }
            line.append(word);
        }
        if (line.length() > 0) {
            out.add(line.toString());
        }
        return out;
    }

    private static String lower(String S) {
        if (S == null || S.isEmpty()) return S;
        return Character.toLowerCase(S.charAt(0)) + S.substring(1);
    }

    private static String upper(String S) {
        if (S == null || S.isEmpty()) return S;
        return Character.toUpperCase(S.charAt(0)) + S.substring(1);
    }

    private void bump(String Key) {
        Integer v = this.counts.get(Key);
        if (v == null) v = Integer.valueOf(0);
        this.counts.put(Key, Integer.valueOf(v.intValue() + 1));
    }

    private static String header() {
        return "/*\n"
             + " * Copyright 2026 Austin Lehman\n"
             + " *\n"
             + " * Licensed under the Apache License, Version 2.0.\n"
             + " * " + MARKER + ". Do not edit.\n"
             + " */\n\n";
    }
