    /**
     * Reports Paper types that share a simple name.
     *
     * Modules and shims are named after a type's simple name, so when two
     * types share one the second overwrites the first and its API is lost.
     * The winner is deterministic, since types are walked in sorted order,
     * but it is chosen by accident of naming rather than on purpose.
     *
     * Reported rather than resolved. Renaming the modules would change what
     * scripts call these types, which is a decision about the script API and
     * not one the generator should take on its own.
     *
     * @throws IOException on a write failure.
     */
    private void reportCollisions() throws IOException {
        Map<String, List<String>> bySimple = new TreeMap<String, List<String>>();
        for (Class<?> c : this.types.values()) {
            List<String> g = bySimple.get(c.getSimpleName());
            if (g == null) {
                g = new ArrayList<String>();
                bySimple.put(c.getSimpleName(), g);
            }
            g.add(c.getName());
        }
        StringBuilder sb = new StringBuilder();
        sb.append("# Types sharing a simple name\n\n");
        sb.append("Generated by com.lehman.aussomcraft.gen.Generator. Do not edit.\n\n");
        sb.append("A module and its Java shim are named after the type's simple name.\n");
        sb.append("Where two Paper types share one, the last in sorted order wins and\n");
        sb.append("the others are not generated at all. Their API is unreachable from a\n");
        sb.append("script, and an object of a losing type wrapped by simple name gets\n");
        sb.append("the winner's shim, which refuses the call rather than running it.\n\n");
        int n = 0;
        StringBuilder body = new StringBuilder();
        for (Map.Entry<String, List<String>> e : bySimple.entrySet()) {
            if (e.getValue().size() < 2) {
                continue;
            }
            n++;
            body.append(e.getKey()).append('\n');
            for (int i = 0; i < e.getValue().size(); i++) {
                String mark = "  lost   ";
                if (i == e.getValue().size() - 1) {
                    mark = "  KEPT   ";
                }
                body.append(mark).append(e.getValue().get(i)).append('\n');
            }
        }
        sb.append("Colliding names: ").append(n).append("\n\n```\n").append(body).append("```\n");
        Files.write(this.ausOut.resolve("NAME-COLLISIONS.md"),
            sb.toString().getBytes(StandardCharsets.UTF_8));
        System.out.println("name collisions : " + n);
    }

